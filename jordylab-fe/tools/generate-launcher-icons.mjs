#!/usr/bin/env bun
// Writes the Android launcher icon of every theme from themes.js: a background colour and an adaptive icon per theme, the
// flask-J mark in the theme's accent colours. The manifest has one activity-alias per theme (AndroidManifest.xml), switched at
// runtime by the LauncherIcon plugin.
//
//   bun tools/generate-launcher-icons.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { themes } from '../themes.js';

const resources = join(import.meta.dirname, '..', 'apps', 'jordylab-mobile', 'android', 'app', 'src', 'main', 'res');

function foreground(ink) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate-launcher-icons.mjs. The JordyLab "J" mark (same glyph as apps/jordylab/public/favicon.svg, 48-unit grid) scaled into the adaptive-icon safe zone. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:translateX="19.2"
        android:translateY="17.2"
        android:scaleX="1.6"
        android:scaleY="1.6">
        <path
            android:fillColor="#00000000"
            android:pathData="M30,10 V27 C30,32.5 26,36 21,36 C17.5,36 15,34.5 13.5,32"
            android:strokeColor="${ink}"
            android:strokeLineCap="round"
            android:strokeLineJoin="round"
            android:strokeWidth="6.5" />
        <path
            android:fillColor="${ink}"
            android:pathData="M13.4,21 a3.6,3.6 0 1,0 7.2,0 a3.6,3.6 0 1,0 -7.2,0" />
        <path
            android:fillColor="${ink}"
            android:pathData="M19.1,12.5 a2.4,2.4 0 1,0 4.8,0 a2.4,2.4 0 1,0 -4.8,0" />
    </group>
</vector>
`;
}

function adaptiveIcon(themeId) {
  return `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background_${themeId}"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground_${themeId}"/>
</adaptive-icon>
`;
}

const colors = themes.map((theme) => `    <color name="ic_launcher_background_${theme.id}">${theme.tokens['accent']}</color>`).join('\n');

mkdirSync(join(resources, 'drawable-v24'), { recursive: true });
mkdirSync(join(resources, 'mipmap-anydpi-v26'), { recursive: true });
for (const theme of themes) {
  writeFileSync(join(resources, 'drawable-v24', `ic_launcher_foreground_${theme.id}.xml`), foreground(theme.tokens['accent-ink']));
  writeFileSync(join(resources, 'mipmap-anydpi-v26', `ic_launcher_${theme.id}.xml`), adaptiveIcon(theme.id));
  writeFileSync(join(resources, 'mipmap-anydpi-v26', `ic_launcher_${theme.id}_round.xml`), adaptiveIcon(theme.id));
}
writeFileSync(
  join(resources, 'values', 'ic_launcher_themes.xml'),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate-launcher-icons.mjs from themes.js. -->
<resources>
${colors}
</resources>
`,
);
console.log(`Wrote launcher icons for ${themes.length} themes.`);
